/*
 * Rasterises the dark-mode app icon into tray-sized PNGs.
 *
 * Electron's nativeImage cannot read SVG, and build/ is the electron-builder
 * resources directory, so it is not available inside a packaged app. The
 * bitmaps are therefore inlined into electron/main/trayIcon.ts as data URLs,
 * which works identically in dev and in a packaged build.
 *
 * Run with:  npm run generate:tray-icon
 */
const { app, BrowserWindow } = require('electron');
const { readFileSync, writeFileSync } = require('fs');
const { join, resolve } = require('path');

const ROOT = resolve(__dirname, '..');
const SOURCE_SVG = join(ROOT, 'src/renderer/taskoverflow-dark-icon.svg');
const OUTPUT_TS = join(ROOT, 'electron/main/trayIcon.ts');
const SIZES = [32, 64];

/** Render the SVG at `size` px on a transparent surface and return a PNG buffer. */
async function rasterize(win, svg, size) {
  win.setContentSize(size, size);

  const html = `<!doctype html><html><head><style>
    html,body{margin:0;padding:0;background:transparent;overflow:hidden}
    svg{display:block;width:${size}px;height:${size}px}
  </style></head><body>${svg}</body></html>`;

  await win.loadURL('data:text/html;charset=utf-8,' + encodeURIComponent(html));
  // Give the compositor a frame to paint before grabbing pixels.
  await new Promise((r) => setTimeout(r, 150));
  const image = await win.capturePage();
  return image.toPNG();
}

app.disableHardwareAcceleration();

app.whenReady().then(async () => {
  const svg = readFileSync(SOURCE_SVG, 'utf8');
  const entries = [];

  const win = new BrowserWindow({
    show: false,
    frame: false,
    transparent: true,
    backgroundColor: '#00000000',
    useContentSize: true,
    webPreferences: { offscreen: true }
  });

  for (const size of SIZES) {
    const png = await rasterize(win, svg, size);
    entries.push({ size, dataUrl: `data:image/png;base64,${png.toString('base64')}` });
    console.log(`rendered ${size}x${size} (${png.length} bytes)`);
  }

  win.destroy();

  const body = entries
    .map((e) => `export const TRAY_ICON_${e.size} =\n  '${e.dataUrl}';`)
    .join('\n\n');

  writeFileSync(
    OUTPUT_TS,
    `// Generated by scripts/generate-tray-icon.cjs from ${'src/renderer/taskoverflow-dark-icon.svg'}.\n` +
      `// Do not edit by hand; run \`npm run generate:tray-icon\` instead.\n\n` +
      `${body}\n`,
    'utf8'
  );

  console.log(`wrote ${OUTPUT_TS}`);
  app.quit();
});
